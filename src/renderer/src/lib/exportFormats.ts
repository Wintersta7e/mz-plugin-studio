// Export format generators for MZ Plugin Studio
// Generates plugins.json entries, TypeScript declarations, and README files

import {
  ID_BASED_PARAM_TYPES,
  type ParamType,
  type PluginCommand,
  type PluginDefinition,
  type PluginMeta,
  type PluginParameter,
  type PluginStruct
} from '../types/plugin'
import { annotationText, escapeBlockComment, escapeLineComment } from './generator/escape'

/**
Generates a JSON entry for plugins.js
Creates the object structure that RPG Maker expects in the plugins.js file
*/
export function generatePluginsJsonEntry(plugin: PluginDefinition): string {
  // Each parameter under the name and default its header holds; `@parent` only nests the
  // editor's list, and a parameter with no default is stored empty. Built from entries, so a
  // parameter named `__proto__` is a key and not the object's prototype
  const parameters: Record<string, string> = Object.fromEntries(
    plugin.parameters.map((param) => [
      annotationText(param.name),
      annotationText(String(param.default))
    ])
  )

  const entry = {
    name: plugin.meta.name,
    status: true,
    description: plugin.meta.description,
    parameters
  }

  return JSON.stringify(entry, null, 2)
}

/**
Converts a parameter type to TypeScript type
*/
function paramTypeToTS(type: ParamType): string {
  if (type === 'number' || ID_BASED_PARAM_TYPES.has(type)) return 'number'
  if (type === 'boolean') return 'boolean'
  if (type === 'struct') return 'Record<string, unknown>'
  if (type === 'array') return 'unknown[]'
  return 'string'
}

// A name TypeScript reads as one identifier, as ECMAScript defines it: wider than the
// validator's rule, which is also what the generated code's own names must follow
const TS_IDENTIFIER = /^[\p{ID_Start}$_][\p{ID_Continue}$\u{200C}\u{200D}]*$/u

// Identifiers TypeScript refuses as a namespace name, though a member key may be any of them:
// the reserved words, and `undefined`, which the global of that name already declares
const TS_RESERVED: ReadonlySet<string> = new Set([
  'break',
  'case',
  'catch',
  'class',
  'const',
  'continue',
  'debugger',
  'default',
  'delete',
  'do',
  'else',
  'enum',
  'export',
  'extends',
  'false',
  'finally',
  'for',
  'function',
  'if',
  'import',
  'in',
  'instanceof',
  'new',
  'null',
  'return',
  'super',
  'switch',
  'this',
  'throw',
  'true',
  'try',
  'typeof',
  'var',
  'void',
  'while',
  'with',
  'undefined'
])

/** The interface members for `params`: each keyed as the generated code reads it, quoted when
the key is not an identifier. */
function memberLines(params: PluginParameter[]): string[] {
  return params.flatMap((param) => {
    const key = annotationText(param.name)
    const description = param.desc || param.text
    return [
      `    /** ${escapeBlockComment(description)} */`,
      `    ${TS_IDENTIFIER.test(key) ? key : JSON.stringify(key)}: ${paramTypeToTS(param.type)}`
    ]
  })
}

/**
The namespace a declaration file names the plugin by: its name when TypeScript accepts it, a
reserved word with `_` after it, else the name with each character an identifier cannot hold
replaced by `_`
*/
function namespaceName(name: string): string {
  if (TS_RESERVED.has(name)) return `${name}_`
  if (TS_IDENTIFIER.test(name)) return name
  const repaired = name
    .replaceAll(/[^\p{ID_Continue}$\u{200C}\u{200D}]/gu, '_')
    .replace(/^(?=[^\p{ID_Start}$_])/u, '_')
  return repaired || 'NewPlugin'
}

/**
A TypeScript declaration file (.d.ts) for the plugin, and a note for each name it declares
otherwise than the plugin names it and each command it gives no arguments interface
*/
export function typeDeclaration(plugin: PluginDefinition): { content: string; notes: string[] } {
  const lines: string[] = []
  const notes: string[] = []
  const namespace = namespaceName(plugin.meta.name)
  if (namespace !== plugin.meta.name) {
    notes.push(`plugin name "${plugin.meta.name}" is declared as ${namespace}`)
  }

  lines.push(
    `// Type declarations for ${escapeLineComment(plugin.meta.name)} v${escapeLineComment(plugin.meta.version)}`,
    `// Generated by MZ Plugin Studio`,
    ``,
    `declare namespace ${namespace} {`
  )

  // Generate Parameters interface if there are parameters
  if (plugin.parameters.length > 0) {
    lines.push(`  interface Parameters {`, ...memberLines(plugin.parameters), `  }`, ``)
  }

  // Generate command arg interfaces; a name that is not an identifier cannot name one
  for (const command of plugin.commands) {
    if (command.args.length === 0) continue
    if (!TS_IDENTIFIER.test(command.name)) {
      notes.push(`command "${command.name}" has no Args interface: its name is not an identifier`)
      continue
    }
    lines.push(`  interface ${command.name}Args {`, ...memberLines(command.args), `  }`, ``)
  }

  lines.push(`}`)

  return { content: lines.join('\n'), notes }
}

/**
Generates a TypeScript declaration file (.d.ts) for the plugin
*/
export const generateTypeDeclaration = (plugin: PluginDefinition): string =>
  typeDeclaration(plugin).content

// A parameter the editor lists at the top, not nested under another
const isTopLevel = (param: PluginParameter): boolean =>
  param.parent === undefined || param.parent === ''

/**
The README's dependency section: required plugins and the plugins it loads after
*/
function readmeDependencies(meta: PluginMeta): string[] {
  const orderAfter = meta.orderAfter ?? []
  if (meta.dependencies.length === 0 && orderAfter.length === 0) return []
  const lines = [`## Dependencies`, ``]
  if (meta.dependencies.length > 0) {
    lines.push(
      `**Required plugins:**`,
      ...meta.dependencies.map((dependency) => `- ${dependency}`),
      ``
    )
  }
  if (orderAfter.length > 0) {
    lines.push(
      `**Load order:** Must be placed after:`,
      ...orderAfter.map((order) => `- ${order}`),
      ``
    )
  }
  return lines
}

/**
The README's parameter table, top-level parameters only
*/
function readmeParameters(parameters: PluginParameter[]): string[] {
  const topLevelParams = parameters.filter((param) => isTopLevel(param))
  if (topLevelParams.length === 0) return []
  return [
    `## Parameters`,
    ``,
    `| Parameter | Type | Default | Description |`,
    `|-----------|------|---------|-------------|`,
    ...topLevelParams.map(
      (param) =>
        `| ${param.text} | ${param.type} | ${String(param.default)} | ${param.desc || param.text} |`
    ),
    ``
  ]
}

/**
One command in the README: its title, description and argument table
*/
function readmeCommand(command: PluginCommand): string[] {
  const lines = [`### ${command.text}`, ``]
  if (command.desc) lines.push(command.desc, ``)
  if (command.args.length === 0) return lines
  lines.push(
    `**Arguments:**`,
    ``,
    `| Argument | Type | Description |`,
    `|----------|------|-------------|`,
    ...command.args.map((arg) => `| ${arg.text} | ${arg.type} | ${arg.desc || arg.text} |`),
    ``
  )
  return lines
}

/**
A README section holding `text`, none when `text` is empty
*/
const readmeText = (title: string, text: string): string[] =>
  text ? [`## ${title}`, ``, text, ``] : []

/**
Generates a README.md file for the plugin
*/
export function generateReadme(plugin: PluginDefinition): string {
  const { meta } = plugin
  return [
    `# ${meta.name}`,
    ``,
    `**Version:** ${meta.version} | **Author:** ${meta.author} | **Target:** ${meta.target}`,
    ``,
    ...(meta.description ? [`> ${meta.description}`, ``] : []),
    `## Installation`,
    ``,
    `1. Download \`${meta.name}.js\``,
    `2. Place it in your project's \`js/plugins/\` folder`,
    `3. Enable it in the Plugin Manager`,
    ``,
    ...readmeDependencies(meta),
    ...readmeParameters(plugin.parameters),
    ...(plugin.commands.length > 0
      ? [`## Plugin Commands`, ``, ...plugin.commands.flatMap((command) => readmeCommand(command))]
      : []),
    ...readmeText('Additional Information', meta.help),
    ...readmeText('More Information', meta.url),
    `---`,
    ``,
    `*Generated by [MZ Plugin Studio](https://github.com/Wintersta7e/mz-plugin-studio)*`
  ].join('\n')
}

/**
Format parameter type with constraints for help text display.
Examples: "number", "number, min: 0, max: 100", "struct<MyStruct>", "number[]"
*/
function formatParamTypeInfo(param: PluginParameter): string {
  const typeString = typeName(param)
  const constraints: string[] = []
  if (param.type === 'number') {
    if (param.min !== undefined) constraints.push('min: ' + String(param.min))
    if (param.max !== undefined) constraints.push('max: ' + String(param.max))
    if (param.decimals !== undefined) constraints.push('decimals: ' + String(param.decimals))
  }

  return constraints.length > 0 ? typeString + ', ' + constraints.join(', ') : typeString
}

/**
The type a parameter's help text names: a struct by its struct name, an array by its element type
*/
function typeName(param: PluginParameter): string {
  const structType = param.structType === '' ? undefined : param.structType
  if (structType !== undefined && param.type === 'struct') return 'struct<' + structType + '>'
  if (param.type !== 'array') return param.type
  if (structType !== undefined) return 'struct<' + structType + '>[]'
  return (param.arrayType ?? 'string') + '[]'
}

const SEP_HEAVY = '='.repeat(76)
const SEP_LIGHT = '-'.repeat(76)

/**
A help text section: its title between light rules, then `body`
*/
const helpSection = (title: string, body: string[]): string[] => [
  '',
  SEP_LIGHT,
  ' ' + title,
  SEP_LIGHT,
  ...body
]

/**
The help text's parameter section: top-level parameters, divider parameters left out
*/
function helpParameters(parameters: PluginParameter[]): string[] {
  const topLevelParams = parameters.filter(
    (p) => isTopLevel(p) && !p.name.includes('---') && !p.name.includes('===')
  )
  if (topLevelParams.length === 0) return []
  return helpSection(
    'Parameters',
    topLevelParams.flatMap((param) => [
      '',
      ' ' + (param.text || param.name) + ' (' + formatParamTypeInfo(param) + ')',
      ...(param.desc ? [' '.repeat(3) + param.desc] : []),
      ...(param.default === '' ? [] : ['   Default: ' + String(param.default)])
    ])
  )
}

/**
One command in the help text: its name, description and arguments
*/
function helpCommand(command: PluginCommand): string[] {
  const lines = ['', ' ' + (command.text || command.name)]
  if (command.desc) lines.push(' '.repeat(3) + command.desc)
  if (command.args.length === 0) return lines
  lines.push('   Arguments:')
  for (const arg of command.args) {
    const desc = arg.desc ? ' - ' + arg.desc : ''
    lines.push(' '.repeat(5) + (arg.text || arg.name) + ' (' + arg.type + ')' + desc)
  }
  return lines
}

/**
The help text's struct section: each struct with its fields
*/
const helpStructs = (structs: PluginStruct[]): string[] =>
  structs.length === 0
    ? []
    : helpSection(
        'Structs',
        structs.flatMap((struct) => [
          '',
          ' ' + struct.name,
          '   Fields: ' +
            struct.parameters.map((p) => (p.text || p.name) + ' (' + p.type + ')').join(', ')
        ])
      )

/**
The help text's dependency section: required plugins and the plugins it loads after
*/
function helpDependencies(meta: PluginMeta): string[] {
  const orderAfter = meta.orderAfter ?? []
  const hasDependencies = meta.dependencies.length > 0
  const hasOrderAfter = orderAfter.length > 0
  if (!hasDependencies && !hasOrderAfter) return []
  const body = ['']
  if (hasDependencies) body.push(' Required: ' + meta.dependencies.join(', '))
  if (hasOrderAfter) body.push(' Load After: ' + orderAfter.join(', '))
  return helpSection('Dependencies', body)
}

/**
Generates formatted plain-text help content for the @help annotation.
Uses ASCII box-drawing for monospace display in MZ's plugin manager.
*/
export function generateHelpText(plugin: PluginDefinition): string {
  const { meta } = plugin
  return [
    SEP_HEAVY,
    ' ' + meta.name + ' v' + meta.version,
    ...(meta.author ? [' by ' + meta.author] : []),
    SEP_HEAVY,
    ...(meta.description ? ['', ' ' + meta.description] : []),
    ...helpParameters(plugin.parameters),
    ...(plugin.commands.length > 0
      ? helpSection(
          'Plugin Commands',
          plugin.commands.flatMap((command) => helpCommand(command))
        )
      : []),
    ...helpStructs(plugin.structs),
    ...helpDependencies(meta),
    '',
    SEP_HEAVY,
    ' Changelog',
    SEP_HEAVY,
    '',
    ' v' + meta.version + ' - Initial release',
    '',
    SEP_HEAVY
  ].join('\n')
}
